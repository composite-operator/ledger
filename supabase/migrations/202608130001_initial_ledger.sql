create policy profiles_public_read
on public.profiles for select
to anon, authenticated
using (is_public = true or id = auth.uid());

create policy profiles_owner_update
on public.profiles for update
to authenticated
using (id = auth.uid())
with check (id = auth.uid());

create policy setups_public_read
on public.setups for select
to anon, authenticated
using (
  exists (
    select 1 from public.profiles p
    where p.id = setups.user_id
      and p.is_public = true
      and p.account_status = 'ACTIVE'
  )
  or user_id = auth.uid()
);

create policy setups_owner_insert
on public.setups for insert
to authenticated
with check (
  user_id = auth.uid()
  and exists (
    select 1 from public.profiles p
    where p.id = auth.uid()
      and p.account_status = 'ACTIVE'
  )
);

create policy metrics_public_read
on public.trader_metrics for select
to anon, authenticated
using (
  exists (
    select 1 from public.profiles p
    where p.id = trader_metrics.profile_id
      and p.is_public = true
      and p.account_status = 'ACTIVE'
  )
  or profile_id = auth.uid()
);

